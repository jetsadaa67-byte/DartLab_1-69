void main() {
  // คำสั่งที่ 1 ทำงานทันที
  print('1. เริ่ม');

  // คำสั่งที่ 2 จำลองการหน่วงเวลา 3 วินาที 
  Future.delayed(Duration(seconds: 3)).then((_) {
    // โค้ดในบล็อก .then() จะทำงานก็ต่อเมื่อเวลาผ่านไปครบ 3 วินาทีแล้ว
    print('2. โหลดเสร็จ');
  });

  // คำสั่งที่ 3 ทำงานทันที โดยไม่รอคำสั่งที่ 2
  print('3. จบ');
}