// เพิ่มคีย์เวิร์ด async ที่ฟังก์ชัน main() ตามคำแนะนำ
void main() async {
  print('1. เริ่ม');

  // สร้างฟังก์ชันย่อยแบบ async เพื่อให้เราสามารถใช้ await ภายในนี้ได้
  // โดยไม่ไปบล็อกการทำงานหลักของ main()
  Future<void> loadData() async {
    await Future.delayed(Duration(seconds: 3));
    print('2. โหลดเสร็จ');
  }

  // เรียกใช้ฟังก์ชันโดย "ไม่ใส่" await ข้างหน้า
  // เพื่อปล่อยให้มันไปนับเวลาเบื้องหลัง และให้โปรแกรมวิ่งไปบรรทัดถัดไปทันที
  loadData();

  print('3. จบ');
}